<?php

declare(strict_types=1);

/**
 * Generates src/fine_print/text/_encoding_data.py from the PHP reference's
 * FinePrint\Text\Encodings, so the four base encodings and the glyph-name list
 * are the PHP tables exactly, never retyped.
 *
 *   php scripts/gen_encodings.php > src/fine_print/text/_encoding_data.py
 *
 * FINE_PRINT_PHP_SRC is checked before the sibling checkout.
 */
$root = getenv('FINE_PRINT_PHP_SRC') ?: __DIR__.'/../../fine-print/src';
spl_autoload_register(function (string $class) use ($root): void {
    $prefix = 'FinePrint\\';
    if (strncmp($class, $prefix, strlen($prefix)) === 0) {
        $file = rtrim($root, '/\\').'/'.str_replace('\\', '/', substr($class, strlen($prefix))).'.php';
        if (is_file($file)) {
            require $file;
        }
    }
});

use FinePrint\Text\Encodings;

$out = "\"\"\"GENERATED by scripts/gen_encodings.php from the PHP reference's\n"
    ."FinePrint\\\\Text\\\\Encodings. Never edit by hand: regenerate it.\"\"\"\n\n"
    ."from __future__ import annotations\n\n";

$out .= "#: name -> {code: Unicode code point}\nMAPS: dict[str, dict[int, int]] = {\n";
foreach (['StandardEncoding', 'WinAnsiEncoding', 'MacRomanEncoding', 'PDFDocEncoding'] as $name) {
    $map = Encodings::map($name);
    $out .= '    '.var_export($name, true).": {";
    $pairs = [];
    foreach ($map as $code => $utf8) {
        $pairs[] = $code.': '.mb_ord($utf8, 'UTF-8');
    }
    $out .= implode(', ', $pairs)."},\n";
}
$out .= "}\n\n";

$m = new ReflectionMethod(Encodings::class, 'glyphs');
$glyphs = $m->invoke(null);
$out .= "#: glyph name -> Unicode code point, in the PHP table's order\nGLYPHS: dict[str, int] = {\n";
foreach ($glyphs as $name => $cp) {
    $out .= '    '.var_export((string) $name, true).': '.$cp.",\n";
}
$out .= "}\n";

echo $out;
